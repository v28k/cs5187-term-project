"""Precision ledger per engine x oracle (D4), regenerated from the bug-hunt documents.

Inputs (all under ``docs/bughunt``):

* ``<engine>/candidates.md``: one table row per triaged signature
  (``| Signature | Oracle | Verdict | Notes |``);
* ``<engine>/<ID>-<slug>/report.md``: filing packages; the ``| Status | ... |`` row;
* ``filed.yaml``: package id -> issue / PR links filed upstream.

Verdicts are bucketed as real / false positive / duplicate / not a bug / open, and precision is
real / (real + false positive) per engine and oracle family (duplicates and not-a-bug rows are
reported but left out of precision, as in the course project's RQ2 ledger).
"""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path
from typing import Any

import yaml

ENGINES = ("duckdb", "sqlite", "turso", "datafusion")


def _bucket(verdict: str) -> str:
    v = verdict.lower()
    if "false positive" in v or v.startswith("fp"):
        return "false_positive"
    if "duplicate" in v or "known" in v:
        return "duplicate"
    if "not a bug" in v or "expected" in v:
        return "not_a_bug"
    if "real" in v or "bug" in v:
        return "real"
    return "open"


def _family(oracle: str) -> str:
    o = oracle.lower()
    for k in ("internal", "crash", "panic", "cross-version", "cross-engine", "differential", "tlp", "norec",
              "expr", "rule", "plan"):
        if k in o:
            return {"panic": "crash", "differential": "cross-engine", "expr": "metamorphic", "tlp": "metamorphic",
                    "norec": "metamorphic", "rule": "plan-variant", "plan": "plan-variant",
                    "internal": "internal error"}.get(k, k)
    return o or "?"


def read_candidates(path: Path) -> list[dict[str, str]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 3 and re.fullmatch(r"[0-9a-f]{6,}", cells[0]):
            rows.append({"signature": cells[0], "oracle": cells[1], "verdict": cells[2].replace("*", "")})
    return rows


def build(root: str | Path) -> dict[str, Any]:
    root = Path(root)
    filed = yaml.safe_load((root / "filed.yaml").read_text(encoding="utf-8")) if (root / "filed.yaml").exists() else {}
    table: dict[tuple[str, str], dict[str, int]] = defaultdict(lambda: defaultdict(int))
    packages = []
    for eng in ENGINES:
        d = root / eng
        if (d / "candidates.md").exists():
            for r in read_candidates(d / "candidates.md"):
                table[(eng, _family(r["oracle"]))][_bucket(r["verdict"])] += 1
        for rep in sorted(d.glob("*-*/report.md")):
            text = rep.read_text(encoding="utf-8")
            title = text.splitlines()[0].lstrip("# ").strip()
            m = re.search(r"^\|\s*Status\s*\|\s*(.+?)\s*\|\s*$", text, re.M)
            status = (m.group(1) if m else "?").replace("*", "")
            pid = rep.parent.name
            if pid in (filed or {}):
                links = {k: v for k, v in filed[pid].items() if k != "state"}
                status = "filed" + (": " + ", ".join(f"[{k}]({v})" for k, v in links.items()) if links else "")
                if filed[pid].get("state"):
                    status += f"; {filed[pid]['state']}"
            packages.append({"engine": eng, "id": pid, "title": title, "status": status})
    rows = []
    for (eng, fam), c in sorted(table.items()):
        judged = c["real"] + c["false_positive"]
        rows.append({"engine": eng, "oracle": fam, **{k: c[k] for k in
                     ("real", "false_positive", "duplicate", "not_a_bug", "open")},
                     "precision": round(c["real"] / judged, 3) if judged else None})
    return {"rows": rows, "packages": packages}


def render(led: dict[str, Any]) -> str:
    out = ["# Precision ledger (generated by `pgfuzz ledger`; do not edit)", "",
           "| Engine | Oracle | Real | False positive | Duplicate | Not a bug | Open | Precision |",
           "|---|---|---|---|---|---|---|---|"]
    for r in led["rows"]:
        p = "-" if r["precision"] is None else f"{r['precision']:.0%}"
        out.append(f"| {r['engine']} | {r['oracle']} | {r['real']} | {r['false_positive']} | {r['duplicate']} | "
                   f"{r['not_a_bug']} | {r['open']} | {p} |")
    out += ["", "## Filing packages", "", "| Engine | Package | Status |", "|---|---|---|"]
    for p in led["packages"]:
        out.append(f"| {p['engine']} | {p['title']} | {p['status'][:320]} |")
    return "\n".join(out) + "\n"
