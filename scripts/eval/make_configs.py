"""E4: write the evaluation configs (src/configs/eval/e4_*.yaml) from the tested engine configs.

Every RQ is a set of arms that differ in exactly one generator or executor parameter; all
other settings (grammar, overlays, schema, oracles) come from the base config of the engine,
so a fix to an engine config reaches the evaluation automatically. Run again after changing a
base config. Budgets and trials follow PLAN.md section 6 (scaled to this 4-core machine).

    python scripts/eval/make_configs.py [--seconds 3600] [--trials 4]
"""
import argparse
import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CFG = ROOT / "src" / "configs"
OUT = CFG / "eval"


def base(name):
    raw = yaml.safe_load((CFG / f"{name}.yaml").read_text(encoding="utf-8"))
    raw = yaml.safe_load(yaml.safe_dump(raw).replace("{config_dir}/../", "{config_dir}/../../"))
    for k in ("output_dir", "known_bugs"):
        if isinstance(raw.get(k), str) and raw[k].startswith("../"):
            raw[k] = "../" + raw[k]
    return raw


def arms(raw, variants, executor_variants=None):
    gen = raw["configs"][0]["generator"]
    out = []
    for name, params in variants.items():
        g = copy.deepcopy(gen)
        g["params"].update(params)
        out.append({"name": name, "label": name, "generator": g})
    return out


def write(name, raw, comment, seconds, trials, seed):
    raw = copy.deepcopy(raw)
    raw.update({"experiment": name, "budget": {"seconds": seconds}, "trials": trials, "seed": seed})
    path = OUT / f"{name}.yaml"
    path.write_text(f"# {comment}\n# generated by scripts/eval/make_configs.py; do not edit\n"
                    + yaml.safe_dump(raw, sort_keys=False), encoding="utf-8")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seconds", type=int, default=3600)
    ap.add_argument("--trials", type=int, default=4)
    a = ap.parse_args()
    S, T = a.seconds, a.trials
    made = []
    for eng in ("duckdb", "sqlite", "datafusion"):
        raw = base(eng)
        # RQ2 (C1/C2): rule-firing feedback and rule-targeted generation
        r = copy.deepcopy(raw)
        r["configs"] = arms(raw, {"no_rule_feedback": {"rule_guidance": False, "rule_target": False},
                                  "rule_feedback": {"rule_guidance": True, "rule_target": False},
                                  "rule_targeting": {"rule_guidance": True, "rule_target": True}})
        made.append(write(f"e4_rules_{eng}", r, f"RQ2: rule coverage with/without rule feedback and targeting ({eng})",
                          S, T, 8100))
        # RQ3 (C3): data synthesis
        r = copy.deepcopy(raw)
        r["executor"]["params"]["metamorphic"] = {"measure_partitions": True}
        r["configs"] = arms(raw, {"no_synth": {"data_synth": 0.0}, "synth": {"data_synth": 1.0}})
        made.append(write(f"e4_synth_{eng}", r, f"RQ3: TLP vacuity with/without Z3 data synthesis ({eng})",
                          S, T, 8200))
        # RQ5 (C6): engine test-suite seeds
        r = copy.deepcopy(raw)
        r["configs"] = arms(raw, {"no_seeds": {"seeds": None},
                                  "suite_seeds": {"seeds": f"{{config_dir}}/../../corpus/suites/{eng}",
                                                  "seed_prob": 0.1}})
        made.append(write(f"e4_seeds_{eng}", r, f"RQ5: engine test suites as seeds ({eng}); first run "
                          f"`pgfuzz import-tests <suite> --out corpus/suites/{eng}`", S, T, 8300))
    # RQ4 (C4): cross-engine precision with/without learned normalizers (executor-level: two experiments)
    xv = base("duckdb_vs_sqlite")
    plain = copy.deepcopy(xv)
    plain["executor"]["params"].pop("learned", None)
    for c in plain["configs"]:
        c["label"] = c["label"].replace("(learned)", "(no normalizers)")
    made.append(write("e4_norm_off", plain, "RQ4: DuckDB vs SQLite without learned normalizers", S, T, 8400))
    made.append(write("e4_norm_on", xv, "RQ4: DuckDB vs SQLite with learned normalizers", S, T, 8400))
    for p in made:
        print(p.relative_to(ROOT))


if __name__ == "__main__":
    main()
